import argparse
import json
import sys
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

ROOT_DIR = Path(__file__).resolve().parents[2]
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from sqlalchemy import inspect, text
from sqlalchemy.engine import Connection
from sqlalchemy.schema import AddConstraint, CreateColumn, CreateIndex, UniqueConstraint

import app.models  # noqa: F401
from app.core.database import Base, engine


@dataclass
class DriftItem:
    kind: str
    table: str
    name: str
    detail: str = ""
    sql: str | None = None
    applied: bool = False


def _compile_type(column, conn: Connection) -> str:
    return str(column.type.compile(dialect=conn.dialect))


def _compile_db_type(db_type: Any, conn: Connection) -> str:
    return str(db_type.compile(dialect=conn.dialect))


def _normalize_default(value: Any) -> str:
    if value is None:
        return ""
    return str(value).strip()


def _is_sequence_default(default_value: str) -> bool:
    lowered = default_value.lower()
    return lowered.startswith("nextval(") or "generated by default as identity" in lowered or "generated always as identity" in lowered


def _should_ignore_default_mismatch(column, db_default: str) -> bool:
    if not db_default:
        return False
    if not getattr(column, "primary_key", False):
        return False
    if not getattr(column, "autoincrement", False):
        return False
    return _is_sequence_default(db_default)


def _normalize_column_group(column_names: list[str] | tuple[str, ...] | None) -> tuple[str, ...]:
    return tuple(column_names or [])


def _build_add_column_sql(table_name: str, column, conn: Connection) -> str:
    column_sql = str(CreateColumn(column).compile(dialect=conn.dialect))
    return f'ALTER TABLE "{table_name}" ADD COLUMN {column_sql}'


def _collect_model_unique_constraints(table) -> list[UniqueConstraint]:
    constraints: list[UniqueConstraint] = []
    for constraint in table.constraints:
        if not isinstance(constraint, UniqueConstraint):
            continue
        if not constraint.name:
            continue
        constraints.append(constraint)
    return constraints


def _collect_model_unique_meta(table) -> tuple[set[str], set[tuple[str, ...]]]:
    names: set[str] = set()
    column_groups: set[tuple[str, ...]] = set()

    for constraint in _collect_model_unique_constraints(table):
        if constraint.name:
            names.add(constraint.name)
        column_groups.add(_normalize_column_group([column.name for column in constraint.columns]))

    for index in table.indexes:
        if not index.unique:
            continue
        if index.name:
            names.add(index.name)
        column_groups.add(_normalize_column_group([column.name for column in index.columns]))

    for column in table.columns:
        if not column.unique:
            continue
        column_groups.add((column.name,))

    return names, column_groups


def _collect_db_unique_meta(conn: Connection, table) -> tuple[set[str], set[tuple[str, ...]]]:
    inspector = inspect(conn)
    names: set[str] = set()
    column_groups: set[tuple[str, ...]] = set()

    for constraint in inspector.get_unique_constraints(table.name, schema=table.schema):
        if constraint.get('name'):
            names.add(constraint['name'])
        column_groups.add(_normalize_column_group(constraint.get('column_names')))

    for index in inspector.get_indexes(table.name, schema=table.schema):
        if not index.get('unique'):
            continue
        if index.get('name'):
            names.add(index['name'])
        column_groups.add(_normalize_column_group(index.get('column_names')))

    return names, column_groups


def _sync_missing_columns(conn: Connection, table, apply: bool, drift: list[DriftItem]):
    inspector = inspect(conn)
    db_columns = {
        column['name']: column
        for column in inspector.get_columns(table.name, schema=table.schema)
    }

    for column in table.columns:
        if column.name in db_columns:
            continue

        sql = _build_add_column_sql(table.name, column, conn)
        item = DriftItem(
            kind='missing_column',
            table=table.name,
            name=column.name,
            detail='model column missing in database',
            sql=sql,
        )
        if apply:
            conn.execute(text(sql))
            item.applied = True
        drift.append(item)


def _report_column_drift(conn: Connection, table, drift: list[DriftItem]):
    inspector = inspect(conn)
    db_columns = {
        column['name']: column
        for column in inspector.get_columns(table.name, schema=table.schema)
    }
    model_column_names = {column.name for column in table.columns}

    for column in table.columns:
        db_column = db_columns.get(column.name)
        if db_column is None:
            continue

        model_type = _compile_type(column, conn)
        db_type = _compile_db_type(db_column['type'], conn)
        if model_type != db_type:
            drift.append(
                DriftItem(
                    kind='type_mismatch',
                    table=table.name,
                    name=column.name,
                    detail=f'model={model_type}, db={db_type}',
                )
            )

        model_nullable = bool(column.nullable)
        db_nullable = bool(db_column['nullable'])
        if model_nullable != db_nullable:
            drift.append(
                DriftItem(
                    kind='nullable_mismatch',
                    table=table.name,
                    name=column.name,
                    detail=f'model={model_nullable}, db={db_nullable}',
                )
            )

        model_default = _normalize_default(getattr(column.server_default, 'arg', None))
        db_default = _normalize_default(db_column.get('default'))
        if model_default != db_default and not _should_ignore_default_mismatch(column, db_default):
            drift.append(
                DriftItem(
                    kind='default_mismatch',
                    table=table.name,
                    name=column.name,
                    detail=f"model={model_default or '<empty>'}, db={db_default or '<empty>'}",
                )
            )

    for db_column_name in db_columns:
        if db_column_name in model_column_names:
            continue
        drift.append(
            DriftItem(
                kind='extra_column',
                table=table.name,
                name=db_column_name,
                detail='database column missing in model',
            )
        )


def _sync_missing_indexes(conn: Connection, table, apply: bool, drift: list[DriftItem]):
    inspector = inspect(conn)
    db_indexes = {
        index['name']: index
        for index in inspector.get_indexes(table.name, schema=table.schema)
        if index.get('name')
    }
    model_unique_names, model_unique_groups = _collect_model_unique_meta(table)

    model_index_names = set()
    for index in table.indexes:
        if not index.name:
            continue
        model_index_names.add(index.name)
        if index.name in db_indexes:
            continue

        sql = str(CreateIndex(index).compile(dialect=conn.dialect))
        item = DriftItem(
            kind='missing_index',
            table=table.name,
            name=index.name,
            detail='model index missing in database',
            sql=sql,
        )
        if apply:
            conn.execute(text(sql))
            item.applied = True
        drift.append(item)

    for db_index_name, db_index in db_indexes.items():
        if db_index_name in model_index_names:
            continue
        if db_index.get('unique'):
            db_group = _normalize_column_group(db_index.get('column_names'))
            if db_index_name in model_unique_names or db_group in model_unique_groups:
                continue
        drift.append(
            DriftItem(
                kind='extra_index',
                table=table.name,
                name=db_index_name,
                detail='database index missing in model',
            )
        )


def _sync_missing_unique_constraints(conn: Connection, table, apply: bool, drift: list[DriftItem]):
    db_unique_names, db_unique_groups = _collect_db_unique_meta(conn, table)
    model_unique_names, model_unique_groups = _collect_model_unique_meta(table)

    for constraint in _collect_model_unique_constraints(table):
        column_group = _normalize_column_group([column.name for column in constraint.columns])
        if constraint.name in db_unique_names or column_group in db_unique_groups:
            continue

        sql = str(AddConstraint(constraint).compile(dialect=conn.dialect))
        item = DriftItem(
            kind='missing_unique_constraint',
            table=table.name,
            name=constraint.name,
            detail='model unique constraint missing in database',
            sql=sql,
        )
        if apply:
            conn.execute(text(sql))
            item.applied = True
        drift.append(item)

    for db_unique_name in db_unique_names:
        if db_unique_name in model_unique_names:
            continue
        drift.append(
            DriftItem(
                kind='extra_unique_constraint',
                table=table.name,
                name=db_unique_name,
                detail='database unique constraint or unique index missing in model',
            )
        )

    for db_unique_group in db_unique_groups:
        if db_unique_group in model_unique_groups:
            continue
        drift.append(
            DriftItem(
                kind='extra_unique_definition',
                table=table.name,
                name=','.join(db_unique_group) or '<unknown>',
                detail='database unique definition missing in model',
            )
        )


def sync_schema(apply: bool = False) -> list[DriftItem]:
    drift: list[DriftItem] = []

    with engine.begin() as conn:
        Base.metadata.create_all(bind=conn, checkfirst=True)

        for table in Base.metadata.sorted_tables:
            _sync_missing_columns(conn, table, apply=apply, drift=drift)
            _report_column_drift(conn, table, drift=drift)
            _sync_missing_indexes(conn, table, apply=apply, drift=drift)
            _sync_missing_unique_constraints(conn, table, apply=apply, drift=drift)

    return drift


def main():
    parser = argparse.ArgumentParser(description='Sync database schema from SQLAlchemy models.')
    parser.add_argument('--apply', action='store_true', help='Apply safe fixes for missing columns/indexes/constraints.')
    parser.add_argument('--json', action='store_true', help='Print drift report as JSON.')
    args = parser.parse_args()

    drift = sync_schema(apply=args.apply)
    payload = [asdict(item) for item in drift]

    if args.json:
        print(json.dumps(payload, ensure_ascii=False, indent=2))
        return

    if not payload:
        print('No schema drift detected.')
        return

    for item in payload:
        prefix = '[applied]' if item['applied'] else '[found]'
        print(f"{prefix} {item['kind']} {item['table']}.{item['name']}")
        if item['detail']:
            print(f"  detail: {item['detail']}")
        if item['sql']:
            print(f"  sql: {item['sql']}")


if __name__ == '__main__':
    main()
